'use strict';
const assert=require('assert');
const R=require('../../../../tools/repair-full-backup');
const S=require('../../main/assets/js/state-core');
const B=require('../../main/assets/js/backup-core');
const state={schemaVersion:16,institutions:[],accounts:[{id:'a',type:'bank',currency:'AED',country:'UAE'}],paymentInstruments:[],transactions:[{id:'t',type:'expense',amount:10,accountId:'a'}],beneficiaries:[],settings:{},categories:{},tags:[],recurring:[]};
const bytes=Buffer.from(JSON.stringify(B.makeFullBackup({state,fingerprint:S.stateFingerprint,features:{privacy:{hideAmounts:true}},receipts:[]})));
const proposal={kind:'nonposting-promotion',id:'t',action:'quarantine-after-approval',confidence:'confirmed',before:state.transactions[0],after:{transaction:null},reason:'offer, not a posted charge'};
const plan={sourceBackupSha256:R.sha(bytes),proposals:[proposal]};
assert.throws(()=>R.applyRepair(bytes,plan,[]),/explicit-approved/);
assert.throws(()=>R.applyRepair(Buffer.concat([bytes,Buffer.from(' ')]),plan,['t']),/source-backup-changed/);
assert.throws(()=>R.applyRepair(bytes,{...plan,proposals:[{...proposal,before:{...proposal.before,amount:11}}]},['t']),/before-image-changed/);
assert.throws(()=>R.applyRepair(bytes,{...plan,proposals:[{...proposal,action:'review-only'}]},['t']),/unresolved/);
assert.throws(()=>R.applyRepair(bytes,plan,['t','t']),/duplicate-approval/);
const repaired=R.applyRepair(bytes,plan,['t']);
assert.strictEqual(JSON.parse(repaired.repairedBytes).finance.transactions.length,0);
assert.strictEqual(repaired.journal.entries[0].before.amount,10);
assert.deepStrictEqual(JSON.parse(repaired.repairedBytes).features,JSON.parse(bytes).features);
assert.strictEqual(B.validateFullEnvelope(JSON.parse(repaired.repairedBytes),S.stateFingerprint).finance.schemaVersion,16);
assert.deepStrictEqual(R.rollback(repaired.repairedBytes,repaired.journal),bytes);
assert.throws(()=>R.applyRepair(repaired.repairedBytes,plan,['t']),/source-backup-changed/);
assert.throws(()=>R.rollback(Buffer.concat([repaired.repairedBytes,Buffer.from(' ')]),repaired.journal),/stop-rollback/);
assert.throws(()=>R.rollback(repaired.repairedBytes,{...repaired.journal,originalBase64:'AAAA'}),/journal-original-corrupt/);
console.log('Guarded backup repair and exact rollback: PASS');
